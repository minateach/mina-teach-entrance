import assert from "node:assert/strict";
import { browserDriver } from "./browser-driver.mjs";

if (!process.env.REPLIT_DEV_DOMAIN) throw new Error("REPLIT_DEV_DOMAIN is required.");
const origin = `https://${process.env.REPLIT_DEV_DOMAIN}`;
const browser = await browserDriver();
const { command, evaluate, waitFor } = browser;
let currentUser = "user_A";
const writes = { preferences: [], conversations: [] };
const chatRequests = [];
let chatAttempt = 0;
async function waitForCondition(check, description) {
  const deadline = Date.now() + 5_000;
  while (!check()) {
    if (Date.now() > deadline) throw new Error(`Timed out waiting for ${description}.`);
    await new Promise(resolve => setTimeout(resolve, 20));
  }
}
const records = {
  user_A: {
    conversations: [{
      id: "account-a-session",
      title: "Private history for learner A",
      grade: 10,
      language: "auto",
      updatedAt: "2026-11-20T10:00:00.000Z",
      messages: [],
    }],
    preferences: {
      assistantMemory: [{ id: "memory-a", text: "Use worked examples", updatedAt: "2026-11-20T10:00:00.000Z" }],
      assistantMemoryEnabled: false,
    },
  },
  user_B: {
    conversations: [{
      id: "account-b-session",
      title: "Private history for learner B",
      grade: 9,
      language: "en",
      updatedAt: "2026-11-21T10:00:00.000Z",
      messages: [],
    }],
    preferences: {
      assistantMemory: [{ id: "memory-b", text: "Use diagrams", updatedAt: "2026-11-21T10:00:00.000Z" }],
      assistantMemoryEnabled: false,
    },
  },
};

try {
  await command("Emulation.setDeviceMetricsOverride", {
    width: 390, height: 844, deviceScaleFactor: 1, mobile: true,
  });
  await browser.intercept(async request => {
    const url = new URL(request.url);
    if (url.pathname === "/api/assistant/status") {
      return {
        body: {
          provider: "minimax",
          configured: true,
          minimaxConfigured: false,
          geminiConfigured: true,
          message: "The MiniMax connection rejected access. Reconnect it in Replit Integrations.",
        },
      };
    }
    if (url.pathname === "/api/account/status") {
      return { body: { signedIn: true, userId: currentUser } };
    }
    if (url.pathname === "/api/account/data" && request.method === "GET") {
      return { body: { records: records[currentUser] } };
    }
    if (url.pathname.startsWith("/api/account/data/") && request.method === "PUT") {
      const type = url.pathname.split("/").at(-1);
      const payload = JSON.parse(request.postData || "{}");
      if (payload.expectedUserId !== currentUser) {
        return { status: 409, body: { error: { code: "ACCOUNT_CHANGED", message: "Account changed." } } };
      }
      if (type === "preferences") {
        writes.preferences.push({ owner: currentUser, data: payload.data });
        records[currentUser].preferences = payload.data;
      }
      if (type === "conversations") {
        writes.conversations.push({ owner: currentUser, data: payload.data });
        records[currentUser].conversations = payload.data;
      }
      return { body: { saved: true } };
    }
    if (url.pathname === "/api/assistant/chat") {
      const payload = JSON.parse(request.postData || "{}");
      chatRequests.push(payload);
      chatAttempt += 1;
      if (chatAttempt === 1) {
        return {
          body: {
            answer: "I will translate the English question, then explain each step in Afaan Oromoo.",
            provider: "gemini",
            providerNotice: "MiniMax is unavailable. This real answer was generated by Gemini; no web search was performed.",
            webResearch: {
              searched: false,
              notice: "No web search was performed; Gemini provided this fallback answer from model knowledge.",
              sources: [],
            },
          },
        };
      }
      if (chatAttempt === 2) {
        return {
          status: 502,
          body: {
            error: {
              code: "DUAL_PROVIDER_UNAVAILABLE",
              message: "MiniMax is unavailable and Gemini could not provide a fallback. No answer was generated.",
            },
          },
        };
      }
      return {
        body: {
          answer: "I will translate the English question, then explain each step in Afaan Oromoo.",
          provider: "minimax",
          webResearch: {
            searched: false,
            notice: "No web search was performed; this answer is from general model knowledge.",
            sources: [],
          },
        },
      };
    }
    return { status: 404, body: { error: { message: `Unexpected request: ${url.pathname}` } } };
  }, ["*api/assistant/status", "*api/account/status", "*api/account/data*", "*api/assistant/chat"]);

  await command("Page.navigate", { url: `${origin}/assistant/` });
  await waitFor('document.readyState==="complete" && document.getElementById("memoryAddButton")');
  await waitFor('document.querySelector(".history-item")?.textContent.includes("Private history for learner A")');
  await waitFor('document.getElementById("memoryInput").disabled===false');
  assert.match(await evaluate('document.getElementById("statusText").textContent'), /MiniMax needs attention/);

  await evaluate('document.getElementById("memoryToggle").click()');
  await evaluate('document.getElementById("memoryInput").value="Show algebra steps clearly";document.getElementById("memoryAddForm").requestSubmit()');
  await waitFor('document.querySelector("#memoryList").textContent.includes("Show algebra steps clearly")');
  await waitForCondition(() => writes.preferences.length >= 1, "first saved memory update");
  await evaluate('document.getElementById("memoryEnabled").checked=true;document.getElementById("memoryEnabled").dispatchEvent(new Event("change",{bubbles:true}))');
  await waitForCondition(() => writes.preferences.length >= 2, "opt-in preference sync");

  await evaluate('document.getElementById("languageSelect").value="om";document.getElementById("languageSelect").dispatchEvent(new Event("change",{bubbles:true}));document.getElementById("messageInput").value="Please explain this English algebra question step by step.";document.getElementById("messageInput").dispatchEvent(new Event("input"));document.getElementById("chatForm").requestSubmit()');
  await waitFor('document.querySelector(".message.assistant .message-content")?.textContent.includes("Afaan Oromoo")');
  assert.equal(await evaluate('document.querySelector(".provider-badge")?.textContent'), "Gemini fallback");
  assert.match(await evaluate('document.getElementById("statusBanner").textContent'), /MiniMax is unavailable/);
  assert.equal(chatRequests[0].language, "om");
  assert.deepEqual(chatRequests[0].studentMemory, ["Use worked examples", "Show algebra steps clearly"]);
  await evaluate('document.getElementById("messageInput").value="Continue with the next step.";document.getElementById("messageInput").dispatchEvent(new Event("input"));document.getElementById("chatForm").requestSubmit()');
  await waitFor('document.querySelector(".error-card")?.textContent.includes("No answer was generated")');
  assert.equal(await evaluate('document.querySelectorAll(".message.assistant").length'), 1, "double provider failure is not displayed as an answer");
  await evaluate('document.querySelector(".retry-button").click()');
  await waitFor('document.querySelectorAll(".message.assistant").length===2');
  assert.equal(await evaluate('Array.from(document.querySelectorAll(".provider-badge")).at(-1)?.textContent'), "MiniMax");
  assert.equal(chatRequests[2].language, "om");
  assert.deepEqual(chatRequests[2].studentMemory, ["Use worked examples", "Show algebra steps clearly"]);

  await evaluate('document.querySelector("#memoryList .memory-item-actions button").click()');
  await evaluate('document.querySelector("#memoryList input").value="Use compact diagrams";document.querySelector("#memoryList form").requestSubmit()');
  await waitFor('document.querySelector("#memoryList").textContent.includes("Use compact diagrams")');
  await waitForCondition(() => !writes.preferences.at(-1)?.data?.assistantMemory?.some(item => item.text === "Use worked examples"), "edited memory sync");
  await evaluate('document.querySelector("#memoryList .memory-item-actions button:nth-child(2)").click()');
  await waitFor('!document.querySelector("#memoryList").textContent.includes("Use compact diagrams")');
  await waitForCondition(() => !writes.preferences.at(-1)?.data?.assistantMemory?.some(item => item.text === "Use compact diagrams"), "memory deletion sync");
  await evaluate('document.getElementById("newConversationAlt").click()');
  await evaluate('document.querySelector("[data-prompt=\\"practice\\"]").click()');
  await waitForCondition(() => chatRequests.length >= 4, "practice request");
  await waitFor('document.querySelector(".message.assistant .message-content")?.textContent.includes("Afaan Oromoo")');
  assert.match(chatRequests[3].message, /AI-generated practice, not an official past exam/);
  assert.ok(writes.conversations.some(write => write.owner === "user_A" && write.data.length >= 2), "new conversations remain functional");
  assert.ok(writes.preferences.every(write => write.owner === "user_A" && write.data.assistantMemory), "memory updates are sent only to the active account");
  assert.ok(writes.conversations.some(write => write.owner === "user_A" && write.data.some(item => item.title.includes("English algebra"))), "conversation updates are account-scoped");

  currentUser = "user_B";
  await evaluate('window.dispatchEvent(new Event("focus"))');
  await waitFor('document.querySelector(".history-item")?.textContent.includes("Private history for learner B") && !document.querySelector("#historyList").textContent.includes("Private history for learner A")');
  await waitFor('document.querySelector("#memoryList").textContent.includes("Use diagrams") && !document.querySelector("#memoryList").textContent.includes("Use worked examples")');
  assert.equal(await evaluate("document.documentElement.scrollWidth<=innerWidth"), true, "account and memory controls fit mobile width");
  const scopedStorage = await evaluate(`JSON.stringify({a:localStorage.getItem("mina-teach.assistant.conversations.v1:user_A"),b:localStorage.getItem("mina-teach.assistant.conversations.v1:user_B")})`);
  assert.match(scopedStorage, /Private history for learner A|English algebra/);
  assert.match(scopedStorage, /Private history for learner B/);
  assert.deepEqual(browser.exceptions, []);
  console.log("PASS: account-scoped chat history, user-added/editable/removable memory, opt-in memory forwarding, English-to-Afaan Oromoo request settings, explicit MiniMax failure, no fabricated response, and Android-width layout.");
} finally {
  await browser.close();
}
